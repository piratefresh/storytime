import React from "react";
import { Command } from "cmdk";

export function Cmdk() {
  const ref = React.useRef<HTMLDivElement | null>(null);
  const [open, setOpen] = React.useState(false);
  const [inputValue, setInputValue] = React.useState("");

  const [pages, setPages] = React.useState<string[]>(["home"]);
  const activePage = pages[pages.length - 1];
  const isHome = activePage === "home";

  // Toggle the menu when ⌘K is pressed
  React.useEffect(() => {
    const down = (e: KeyboardEvent) => {
      if (e.key === "k" && (e.metaKey || e.ctrlKey)) {
        e.preventDefault();
        setOpen((prev) => !prev);
      }
    };

    document.addEventListener("keydown", down);
    return () => { document.removeEventListener("keydown", down); };
  }, []);

  const popPage = React.useCallback(() => {
    setPages((prev) => {
      const x = [...prev];
      x.splice(-1, 1);
      return x;
    });
  }, []);

  function bounce() {
    if (ref.current) {
      ref.current.style.transform = "scale(0.96)";
      setTimeout(() => {
        if (ref.current) {
          ref.current.style.transform = "";
        }
      }, 100);

      setInputValue("");
    }
  }

  return (
    <Command.Dialog
      className="fixed top-1/2 left-1/2 transform -translate-x-1/2 -translate-y-1/2 max-w-[640px] w-full p-2 bg-white rounded-lg overflow-hidden font-sans border border-gray-600 shadow transition-transform duration-100 ease-in-out outline-none dark:bg-[rgba(22,22,22,0.7)]"
      open={open}
      onOpenChange={setOpen}
      ref={ref}
      onKeyDown={(e: React.KeyboardEvent) => {
        if (e.key === "Enter") {
          bounce();
        }

        if (isHome || inputValue.length) {
          return;
        }

        if (e.key === "Backspace") {
          e.preventDefault();
          popPage();
          bounce();
        }
      }}
    >
      <div>
        {pages.map((p) => (
          <div key={p} data-cmdk-vercel-badge="">
            {p}
          </div>
        ))}
      </div>
      <Command.Input
        placeholder="What do you need?"
        onValueChange={(value) => {
          setInputValue(value);
        }}
      />
      <Command.List>
        <Command.Empty>No results found.</Command.Empty>
        {activePage === "home" && (
          <Home searchProjects={() => { setPages([...pages, "projects"]); }} />
        )}
        {activePage === "projects" && <Projects />}
      </Command.List>
    </Command.Dialog>
  );
}

